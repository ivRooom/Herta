export const FORTUNE_PATTERN_COUNT = FOCUSES.length * PERSPECTIVES.length;

export function fortunePatternAt(index: number) {
  if (!Number.isInteger(index) || index < 0 || index >= FORTUNE_PATTERN_COUNT)
    throw new RangeError('Invalid fortune pattern');
  const focus = FOCUSES[Math.floor(index / PERSPECTIVES.length)]!;
  const perspective = PERSPECTIVES[index % PERSPECTIVES.length]!;
  const color = COLORS[(Math.floor(index / PERSPECTIVES.length) + index) % COLORS.length]!;
  return {
    patternId: `editorial-v2-${index}`,
    title: `${focus[0]}・${perspective[0]}`,
    message: `${focus[1]}${perspective[1]}`,
    item: focus[2],
    action: `${focus[3]}。${perspective[2]}`,
    color: color[0],
    hex: color[1],
  };
}

/** A full permutation for each subject: no text-pattern repeat for 1,024 consecutive dates. */
export function dailyFortunePattern(guildId: string, userId: string, date: string) {
  const day = Date.parse(`${date}T00:00:00.000Z`) / 86_400_000;
  if (!Number.isInteger(day) || new Date(day * 86_400_000).toISOString().slice(0, 10) !== date)
    throw new RangeError('Invalid fortune date');
  const seed = createHash('sha256')
    .update(JSON.stringify(['herta-fortune-text-v2', guildId, userId]))
    .digest();
  const offset = seed.readUInt32BE(0) % FORTUNE_PATTERN_COUNT;
  const step = (seed.readUInt32BE(4) % (FORTUNE_PATTERN_COUNT / 2)) * 2 + 1;
  const index =
    (((offset + day * step) % FORTUNE_PATTERN_COUNT) + FORTUNE_PATTERN_COUNT) %
    FORTUNE_PATTERN_COUNT;
  return fortunePatternAt(index);
}
